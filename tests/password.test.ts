import { describe, expect, it } from 'vitest'

import { hashPassword, verifyPassword } from '../lib/auth/password'

describe('password hashing', () => {
  it('hashes and verifies a password', async () => {
    const hash = await hashPassword('secret-password')

    expect(await verifyPassword('secret-password', hash)).toBe(true)
    expect(await verifyPassword('wrong-password', hash)).toBe(false)
  })

  it('verifies a bcrypt hash generated by PHP/Laravel', async () => {
    // Generated with PHP password_hash('password', PASSWORD_BCRYPT) — the
    // format Laravel uses for its `users.password` column.
    const laravelHash = '$2y$10$FaZhk9ZWSJhUIe2IvCfy4uG6t1x02eDssJzDoQBhKUAHjjrhHY79G'

    expect(await verifyPassword('password', laravelHash)).toBe(true)
    expect(await verifyPassword('wrong', laravelHash)).toBe(false)
  })
})
